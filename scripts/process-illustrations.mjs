#!/usr/bin/env node
// Render the illustration library from its originals.
//
// Originals are 1536×1024 PNGs (ChatGPT image generation, see
// docs/ART_DIRECTION.md) kept OUTSIDE the repo in design-source/raw/, named by
// each manifest entry's `source`. For every raster entry of src/lib/assets.js
// this writes public/images/<category>/<name>-<width>.webp for each width the
// next/image loader serves (src/lib/image-loader.js), and records the image's
// average colour (the loading placeholder) in src/lib/asset-colors.js.
//
//   npm run assets:process                                   → every asset
//   node scripts/process-illustrations.mjs landing.hero …    → only these ids
//   node scripts/process-illustrations.mjs --src <dir>       → originals elsewhere
//                                                              (default ../design-source/raw)
import { existsSync, mkdirSync, readdirSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import sharp from "sharp";
import { ASSET_LIST } from "../src/lib/assets.js";
import { IMAGE_WIDTHS } from "../src/lib/image-loader.js";

const args = process.argv.slice(2);
const srcFlag = args.indexOf("--src");
const SRC_DIR = srcFlag >= 0 ? args[srcFlag + 1] : join("..", "design-source", "raw");
const only = new Set(args.filter((a, i) => !a.startsWith("--") && args[i - 1] !== "--src"));
const COLORS = join("src", "lib", "asset-colors.js");

// Larger renditions hide compression better, so they can use a lower quality.
const quality = (w) => (w >= 1280 ? 70 : w >= 640 ? 74 : 80);

const colors = existsSync(COLORS) ? { ...(await import(pathToFileURL(COLORS).href)).default } : {};
const targets = ASSET_LIST.filter((a) => a.kind === "raster" && (!only.size || only.has(a.id)));
if (only.size && targets.length !== only.size) {
  const known = new Set(targets.map((a) => a.id));
  console.error(`unknown ids: ${[...only].filter((id) => !known.has(id)).join(", ")}`);
  process.exit(1);
}

let total = 0;
for (const a of targets) {
  const input = join(SRC_DIR, `${a.source}.png`);
  if (!existsSync(input)) {
    console.error(`✗ ${a.id}: original not found at ${input}`);
    process.exitCode = 1;
    continue;
  }
  const meta = await sharp(input).metadata();
  if (meta.width !== a.width || meta.height !== a.height) {
    console.error(`✗ ${a.id}: original is ${meta.width}×${meta.height}, manifest says ${a.width}×${a.height}`);
    process.exitCode = 1;
    continue;
  }

  const stem = join("public", a.src.slice(1, -".webp".length));
  mkdirSync(dirname(stem), { recursive: true });
  // Drop renditions of this asset that the current width list no longer produces.
  const base = stem.split(/[\\/]/).pop();
  for (const f of readdirSync(dirname(stem))) {
    const m = f.match(/^(.+)-(\d+)\.webp$/);
    if (m && m[1] === base && !IMAGE_WIDTHS.includes(Number(m[2]))) unlinkSync(join(dirname(stem), f));
  }

  const sizes = [];
  for (const w of IMAGE_WIDTHS) {
    const out = `${stem}-${w}.webp`;
    await sharp(input)
      .resize({ width: w, kernel: "lanczos3" })
      .webp({ quality: quality(w), effort: 6, smartSubsample: true })
      .toFile(out);
    const kb = statSync(out).size / 1024;
    total += kb;
    sizes.push(`${w}:${kb.toFixed(0)}K`);
  }

  const { data } = await sharp(input).resize(1, 1, { fit: "fill" }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  colors[a.id] = `#${[...data].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
  console.log(`✓ ${a.id.padEnd(30)} ${sizes.join("  ")}`);
}

// Keep the colour map in manifest order and free of retired ids.
const ordered = {};
for (const a of ASSET_LIST) if (colors[a.id]) ordered[a.id] = colors[a.id];
writeFileSync(
  COLORS,
  `// Generated by scripts/process-illustrations.mjs — average colour of each image (loading placeholder).\nconst ASSET_COLORS = ${JSON.stringify(ordered, null, 2)};\n\nexport default ASSET_COLORS;\n`
);
console.log(`\n${targets.length} asset(s), ${(total / 1024).toFixed(1)} MB written`);
